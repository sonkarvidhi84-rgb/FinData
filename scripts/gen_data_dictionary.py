"""Generate docs/data-dictionary.md from the SQLAlchemy metadata and dataset YAML contracts.

Run: `uv run python scripts/gen_data_dictionary.py`. The output is committed so the docs site
always reflects the schema; regenerate it whenever tables.py or config/datasets changes.
"""

from __future__ import annotations

import sys
from pathlib import Path

from sqlalchemy import ForeignKeyConstraint, Table, UniqueConstraint

from findata.config import dataset_names, load_dataset
from findata.model.tables import metadata
from findata.settings import PROJECT_ROOT

OUT = PROJECT_ROOT / "docs" / "data-dictionary.md"
VIEWS = {
    "v_price_adjusted": (
        "NSE prices with split/dividend-adjusted OHLC: `adjusted_x = x * cumulative_factor`, "
        "where the factor comes from the `adj_factor_segment` covering the trade date "
        "(1.0 when none)."
    )
}


def _esc(text: str | None) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ")


def table_section(table: Table) -> list[str]:
    lines = [f"### `{table.name}`", "", _esc(table.comment), ""]
    uniques = [
        ", ".join(c.name for c in con.columns)
        for con in table.constraints
        if isinstance(con, UniqueConstraint)
    ]
    uniques = list(dict.fromkeys(uniques))
    pk = ", ".join(c.name for c in table.primary_key.columns)
    lines.append(f"**Primary key:** `{pk}`  ")
    if uniques:
        lines.append("**Natural key / unique:** " + "; ".join(f"`({u})`" for u in uniques) + "  ")
    fks = [
        f"`{', '.join(c.name for c in fk.columns)}` → `{fk.referred_table.name}`"
        for fk in table.constraints
        if isinstance(fk, ForeignKeyConstraint)
    ]
    if fks:
        lines.append("**Foreign keys:** " + "; ".join(fks) + "  ")
    lines += ["", "| Column | Type | Null | Description |", "|---|---|---|---|"]
    for col in table.columns:
        null = "yes" if col.nullable else "no"
        lines.append(f"| `{col.name}` | {col.type} | {null} | {_esc(col.comment)} |")
    return [*lines, ""]


def dataset_section(name: str) -> list[str]:
    cfg = load_dataset(name)
    lines = [
        f"### `{cfg.name}`",
        "",
        _esc(cfg.description),
        "",
        f"- **Source:** {cfg.source} — `{cfg.source_url}`",
        f"- **Schedule:** {cfg.schedule}",
        f"- **Grain:** {cfg.grain}",
        f"- **Natural key:** `{', '.join(cfg.natural_key)}`",
    ]
    if cfg.quality:
        q = ", ".join(f"{k}={v}" for k, v in cfg.quality.items())
        lines.append(f"- **Quality thresholds:** {q}")
    if cfg.rules:
        lines.append(f"- **Rules:** {', '.join(f'`{r}`' for r in cfg.rules)}")
    lines += ["", "| Column | Type | Null | Checks | Description |", "|---|---|---|---|---|"]
    for c in cfg.columns:
        checks = []
        if c.pattern:
            checks.append(f"matches `{c.pattern}`")
        if c.gt is not None:
            checks.append(f"> {c.gt:g}")
        if c.ge is not None:
            checks.append(f">= {c.ge:g}")
        if c.isin_set:
            checks.append("in {" + ", ".join(c.isin_set) + "}")
        null = "yes" if c.nullable else "no"
        lines.append(
            f"| `{c.name}` | {c.dtype} | {null} | {_esc('; '.join(checks))} | "
            f"{_esc(c.description)} |"
        )
    return [*lines, ""]


def render() -> str:
    lines = [
        "# Data dictionary",
        "",
        "_Generated by `scripts/gen_data_dictionary.py` from `src/findata/model/tables.py` and "
        "`config/datasets/*.yaml`. Do not edit by hand._",
        "",
        "## Warehouse tables",
        "",
    ]
    for table in metadata.sorted_tables:
        lines += table_section(table)
    lines += ["## Views", ""]
    for name, desc in VIEWS.items():
        lines += [f"### `{name}`", "", desc, ""]
    lines += [
        "## Dataset contracts (staging)",
        "",
        "Every dataset is validated against its YAML contract before it reaches staging.",
        "",
    ]
    for name in dataset_names():
        lines += dataset_section(name)
    return "\n".join(lines).rstrip() + "\n"


def main(out: Path = OUT) -> int:
    out.write_text(render(), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
